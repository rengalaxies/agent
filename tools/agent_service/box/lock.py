"""Regenerate ``infra/agent_service/requirements.lock`` from ``requirements.in``.

The lock pins one exact version per package and lists the sha256 of the wheel
for every supported platform, so ``pip install --require-hashes --no-index``
accepts only these files. Run it on a machine with network access:

    python tools/agent_service/box/lock.py

The first platform resolves the versions; the others must have wheels of the
same versions (no source builds on the target VM).
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[3]
INFRA = ROOT / "infra" / "agent_service"

# (pip --platform values, python version). linux-x86_64-cp312 is the target VM
# (Ubuntu 24.04 python3.12); win-amd64-cp314 is the development machine.
PLATFORMS = {
    "linux-x86_64-cp312": (["manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64"], "3.12"),
    "win-amd64-cp314": (["win_amd64"], "3.14"),
}
WHEEL = re.compile(r"^([A-Za-z0-9_.]+)-([^-]+)-.*\.whl$")


def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def download(platform: str, dest: Path, requirements: list[str], *, no_deps: bool) -> dict[str, tuple[str, str]]:
    tags, python = PLATFORMS[platform]
    cmd = [sys.executable, "-m", "pip", "download", "--quiet", "--disable-pip-version-check", "--only-binary=:all:",
           "--implementation", "cp", "--python-version", python, "-d", str(dest)]
    for tag in tags:
        cmd += ["--platform", tag]
    if no_deps:
        cmd.append("--no-deps")
    subprocess.run(cmd + requirements, check=True)
    found = {}
    for wheel in sorted(dest.iterdir()):
        m = WHEEL.match(wheel.name)
        if not m:
            raise SystemExit(f"not a wheel: {wheel.name}")
        found[canonical(m.group(1))] = (m.group(2), hashlib.sha256(wheel.read_bytes()).hexdigest())
    return found


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=INFRA / "requirements.lock")
    args = parser.parse_args(argv)
    top = [line.split("#")[0].strip() for line in (INFRA / "requirements.in").read_text(encoding="utf-8").splitlines()]
    top = [line for line in top if line]
    names = list(PLATFORMS)
    hashes: dict[str, set[str]] = {}
    with tempfile.TemporaryDirectory() as tmp:
        first = download(names[0], Path(tmp) / names[0], top, no_deps=False)
        pins = [f"{name}=={version}" for name, (version, _) in sorted(first.items())]
        for name, (_, sha) in first.items():
            hashes.setdefault(name, set()).add(sha)
        for platform in names[1:]:
            other = download(platform, Path(tmp) / platform, pins, no_deps=True)
            for name, (version, sha) in other.items():
                if version != first[name][0]:
                    raise SystemExit(f"{name}: {platform} resolved {version}, expected {first[name][0]}")
                hashes[name].add(sha)
    lines = ["# Generated by tools/agent_service/box/lock.py from requirements.in. Do not edit by hand.",
             "# Platforms: " + ", ".join(names)]
    for name, (version, _) in sorted(first.items()):
        lines.append(f"{name}=={version} \\")
        shas = sorted(hashes[name])
        lines += [f"    --hash=sha256:{sha}" + (" \\" if i < len(shas) - 1 else "") for i, sha in enumerate(shas)]
    args.output.write_bytes(("\n".join(lines) + "\n").encode())
    print(f"{len(first)} packages -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
